import type { MDXContent } from "mdx/types";
import type { ContentReference } from "@/types/concept";
import type { CodeLanguage, Technology } from "@/types/technology";
import type { Locale } from "@/types/locale";

export const FOUNDATION_TOPICS = [
  "runtime-lifecycle",
  "state-rendering",
  "concurrency",
  "networking",
  "storage-offline",
  "architecture",
  "navigation-platform",
  "security-privacy",
  "experience-quality",
  "delivery-systems",
] as const;

export const MOBILE_PLATFORMS = ["android", "ios"] as const;
export type FoundationTopic = (typeof FOUNDATION_TOPICS)[number];
export type MobilePlatform = (typeof MOBILE_PLATFORMS)[number];

export type FoundationReference = ContentReference & {
  id: string;
  platforms?: readonly MobilePlatform[];
};

export type FoundationLocaleMetadata = {
  title: string;
  description: string;
  keywords: readonly string[];
  reviewedAt?: string;
};

export type FoundationArticleMetadata = {
  slug: string;
  topic: FoundationTopic;
  order: number;
  status: "draft" | "published";
  platforms: readonly MobilePlatform[];
  technologies?: readonly Technology[];
  locales: Partial<Record<Locale, FoundationLocaleMetadata>>;
  references: readonly FoundationReference[];
  relatedArticles: readonly string[];
  relatedConcepts: readonly string[];
};

export type FoundationHeading = { id: string; text: string; level: number };
export type FoundationFigure = {
  id: string;
  src: string;
  alt: string;
  caption: string;
  sources: readonly string[];
};
export type FoundationSnippet = { path: string; language: CodeLanguage };

/** Generated by the MDX compiler; never maintained separately by authors. */
export type FoundationBodyData = {
  headings: readonly FoundationHeading[];
  citations: readonly string[];
  figures: readonly FoundationFigure[];
  snippets: readonly FoundationSnippet[];
  links: readonly string[];
  hasContent: boolean;
};

export type FoundationBodyModule = {
  default: MDXContent;
  foundation: FoundationBodyData;
};

/** Rendering functions stay server-side and outside serializable metadata. */
export type FoundationDefinition = {
  metadata: FoundationArticleMetadata;
  bodies: Partial<Record<Locale, FoundationBodyModule>>;
};

export type FoundationArticle = {
  metadata: FoundationArticleMetadata;
  locale: Locale;
  localized: FoundationLocaleMetadata;
  body: FoundationBodyModule;
};
